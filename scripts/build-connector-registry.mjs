// Generates src/nexus-admin/connectors/index.generated.ts from the files in
// src/nexus-admin/connectors/defs. Runs before dev, build, test and typecheck,
// so adding a connector is adding one file to defs/.
//
//   node scripts/build-connector-registry.mjs           write the index
//   node scripts/build-connector-registry.mjs --check   fail if it is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export function discover(defsDir) {
  return fs
    .readdirSync(defsDir)
    .filter((f) => /^[a-z0-9][a-z0-9-]*\.ts$/.test(f) && !f.endsWith(".d.ts"))
    .sort();
}

export function render(files, importPrefix = "./defs/") {
  const ident = (f) => `def_${f.replace(/\.ts$/, "").replace(/[^a-z0-9]/g, "_")}`;
  return [
    "// Generated by scripts/build-connector-registry.mjs. Do not edit by hand.",
    "// Add a connector by adding a file to ./defs; this index is rebuilt automatically.",
    'import type { ConnectorDefinition } from "./types";',
    ...files.map((f) => `import ${ident(f)} from "${importPrefix}${f.replace(/\.ts$/, "")}";`),
    "",
    "export const DEFINITIONS: ConnectorDefinition[] = [",
    ...files.map((f) => `  ${ident(f)},`),
    "];",
    "",
  ].join("\n");
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const dir = path.join(root, "src/nexus-admin/connectors");
  const out = path.join(dir, "index.generated.ts");
  const text = render(discover(path.join(dir, "defs")));
  if (process.argv.includes("--check")) {
    const existing = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
    if (existing !== text) {
      console.error("src/nexus-admin/connectors/index.generated.ts is out of date. Run npm run connectors:index.");
      process.exit(1);
    }
  } else if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== text) {
    fs.writeFileSync(out, text);
    console.log(`Connector registry: ${discover(path.join(dir, "defs")).length} definitions.`);
  }
}
