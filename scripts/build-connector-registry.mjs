// Generates the plug-in indexes:
//   src/nexus-admin/connectors/index.generated.ts   from src/nexus-admin/connectors/defs
//   src/investigation/detectors/index.generated.ts  from src/investigation/detectors/defs
// Runs before dev, build, test and typecheck, so adding a connector or a
// detector is adding one file to its defs/ folder.
//
//   node scripts/build-connector-registry.mjs           write the indexes
//   node scripts/build-connector-registry.mjs --check   fail if one is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export function discover(defsDir) {
  if (!fs.existsSync(defsDir)) return [];
  return fs
    .readdirSync(defsDir)
    .filter((f) => /^[a-z0-9][a-z0-9-]*\.ts$/.test(f) && !f.endsWith(".d.ts"))
    .sort();
}

const CONNECTORS = {
  label: "connector",
  dir: "src/nexus-admin/connectors",
  typeName: "ConnectorDefinition",
  typeImport: "./types",
  exportName: "DEFINITIONS",
};
const DETECTORS = {
  label: "detector",
  dir: "src/investigation/detectors",
  typeName: "Detector",
  typeImport: "../types",
  exportName: "DETECTORS",
};

export function render(files, importPrefix = "./defs/", kind = CONNECTORS) {
  const ident = (f) => `def_${f.replace(/\.ts$/, "").replace(/[^a-z0-9]/g, "_")}`;
  return [
    "// Generated by scripts/build-connector-registry.mjs. Do not edit by hand.",
    `// Add a ${kind.label} by adding a file to ./defs; this index is rebuilt automatically.`,
    `import type { ${kind.typeName} } from "${kind.typeImport}";`,
    ...files.map((f) => `import ${ident(f)} from "${importPrefix}${f.replace(/\.ts$/, "")}";`),
    "",
    `export const ${kind.exportName}: ${kind.typeName}[] = [`,
    ...files.map((f) => `  ${ident(f)},`),
    "];",
    "",
  ].join("\n");
}

export const renderDetectors = (files) => render(files, "./defs/", DETECTORS);

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  let stale = false;
  for (const kind of [CONNECTORS, DETECTORS]) {
    const dir = path.join(root, kind.dir);
    if (!fs.existsSync(dir)) continue;
    const out = path.join(dir, "index.generated.ts");
    const files = discover(path.join(dir, "defs"));
    const text = render(files, "./defs/", kind);
    const existing = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
    if (process.argv.includes("--check")) {
      if (existing !== text) {
        console.error(`${kind.dir}/index.generated.ts is out of date. Run npm run connectors:index.`);
        stale = true;
      }
    } else if (existing !== text) {
      fs.writeFileSync(out, text);
      console.log(`${kind.label[0].toUpperCase()}${kind.label.slice(1)} registry: ${files.length} definitions.`);
    }
  }
  if (stale) process.exit(1);
}
